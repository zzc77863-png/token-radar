// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never
// the ceiling) and adds the pre-token protocols below the floor the early
// radar exists to find. A protocol is pre-token when its record carries no
// token at all: no market cap, no CoinGecko id, no symbol.
//
// Implied value is not a flat multiple of TVL. It is priced off the
// snapshot's own comparables: for each category, the median market-cap / TVL
// of the token-bearing protocols in that category, shrunk toward the global
// median so a category with two protocols does not set its own price. The
// same function scores every row; no protocol name is ever special-cased.
//
//   catMult    = (n * median(cat) + 5 * median(all)) / (n + 5), clamped [0.05, 0.90]
//   base       = tvl_usd * catMult
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) * 0.35
//   maturity   = 0.70 + min(age_days, 1095) / 1095 * 0.30   (age unknown: 365)
//   breadth    = 1 + 0.04 * min(chains - 1, 5), capped at 1.20
//   implied    = max(1, round(base * growthMult * maturity * breadth))
//
// Why these four: the comparable multiple says what the market already pays
// per dollar of TVL for this kind of protocol; growth says whether that TVL
// is arriving or leaving; maturity says whether the protocol has survived
// long enough to be a launch candidate rather than a week-old farm; breadth
// says whether it is live on more than one chain. A protocol that records
// no token is never said to have none — only that its record carries none.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

